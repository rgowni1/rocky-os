-- journal_entries: the raw journal plus three generated summaries.
--
-- The narrative columns mirrored Notion properties one-to-one, and most of
-- those properties are never filled: High Of the Week, Stressors, Bud, People
-- Met and Person are empty on all but one or two of 204 weeks. The writing
-- that actually happens is in the page body (day-by-day bullets, and the
-- end-of-week Claude notes), which nothing captured.
--
-- So the table becomes:
--   journal_raw_text  the page body as plain indented text — the source
--   journal_high / journal_low / journal_bud
--                     generated from journal_raw_text by journal_sync.py
--
-- journal_high and journal_low keep their names, and their existing values
-- (the Notion High / Low properties), because the kanban word cloud reads
-- them. journal_sync.py only regenerates a week when its raw text changes, so
-- history is not rewritten by the first sync.

alter table public.journal_entries add column if not exists journal_raw_text text;
-- Bookkeeping: which raw text the summaries were generated from, so a week is
-- regenerated when it is edited and not otherwise.
alter table public.journal_entries add column if not exists journal_summary_of text;

alter table public.journal_entries
  drop column if exists journal_title,
  drop column if exists journal_high_of_week,
  drop column if exists journal_stressors,
  drop column if exists people_met,
  drop column if exists people_tagged,
  drop column if exists unstructured;

comment on column public.journal_entries.journal_raw_text is
  'Notion journal page body as indented plain text. Excludes the synced
   quarterly-goals block and empty template labels.';
comment on column public.journal_entries.journal_high is
  'Generated by journal_sync.py from journal_raw_text (pre-2026-10-11 weeks:
   the Notion High property).';
comment on column public.journal_entries.journal_low is
  'Generated by journal_sync.py from journal_raw_text (pre-2026-10-11 weeks:
   the Notion Low property).';
comment on column public.journal_entries.journal_bud is
  'Generated by journal_sync.py from journal_raw_text: something emerging or
   worth building on.';
comment on column public.journal_entries.journal_summary_of is
  'md5 of the journal_raw_text that journal_high/low/bud were generated from.
   journal_sync.py regenerates when it no longer matches.';
